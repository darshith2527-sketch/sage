import {
  AlignmentType,
  Document,
  Footer,
  Packer,
  PageNumber,
  Paragraph,
  TextRun,
} from "docx";
import type { Contract } from "@/contracts/engine";

const FONT = "Calibri"; // Word's default; includes the ₹ sign on Windows and Mac

// Turns one line of clause text into Word text, highlighting [blanks] in yellow.
function runsFor(line: string): TextRun[] {
  return line
    .split(/(\[[^\]]+\])/g)
    .filter((part) => part.length > 0)
    .map((part) =>
      part.startsWith("[") && part.endsWith("]")
        ? new TextRun({ text: part, font: FONT, highlight: "yellow" })
        : new TextRun({ text: part, font: FONT }),
    );
}

export async function contractToDocx(contract: Contract): Promise<Blob> {
  const body: Paragraph[] = [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 300 },
      children: [new TextRun({ text: contract.title, bold: true, size: 32, font: FONT })],
    }),
  ];

  for (const clause of contract.clauses) {
    body.push(
      new Paragraph({
        spacing: { before: 240, after: 80 },
        keepNext: true, // keep the heading on the same page as its text
        children: [
          new TextRun({ text: `${clause.number}. ${clause.title}`, bold: true, font: FONT }),
        ],
      }),
    );
    // Each line of the clause becomes its own paragraph; empty lines are skipped.
    for (const line of clause.text.split("\n").filter((l) => l.trim())) {
      body.push(new Paragraph({ spacing: { after: 80 }, children: runsFor(line) }));
    }
  }

  // Signature block for both parties.
  for (const party of contract.parties) {
    body.push(
      new Paragraph({ spacing: { before: 480 }, children: [new TextRun({ text: "______________________________", font: FONT })] }),
      new Paragraph({ children: [new TextRun({ text: `Signed by the ${party.role}`, font: FONT })] }),
      new Paragraph({ children: [new TextRun({ text: `Name: ${party.name}`, font: FONT })] }),
      new Paragraph({ children: [new TextRun({ text: "Date:", font: FONT })] }),
    );
  }

  const doc = new Document({
    creator: "Sage",
    title: contract.title,
    styles: { default: { document: { run: { font: FONT, size: 21 } } } }, // 10.5pt
    sections: [
      {
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                children: [
                  new TextRun({ text: "Generated by Sage. Not legal advice. Page ", size: 16, color: "80868B" }),
                  new TextRun({ children: [PageNumber.CURRENT], size: 16, color: "80868B" }),
                ],
              }),
            ],
          }),
        },
        children: body,
      },
    ],
  });

  return Packer.toBlob(doc);
}
