import { Document, Font, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import type { Contract } from "@/contracts/engine";

// Noto Sans, merged so it includes the ₹ sign (the built-in PDF fonts don't have it).
Font.register({
  family: "NotoSans",
  fonts: [
    { src: "/fonts/NotoSans-Regular.ttf" },
    { src: "/fonts/NotoSans-Bold.ttf", fontWeight: 700 },
  ],
});

// Don't split words with hyphens at line ends; legal text should read cleanly.
Font.registerHyphenationCallback((word) => [word]);

const styles = StyleSheet.create({
  page: { fontFamily: "NotoSans", fontSize: 10, lineHeight: 1.5, padding: 56, color: "#202124" },
  title: { fontSize: 16, fontWeight: 700, textAlign: "center", marginBottom: 20 },
  clause: { marginBottom: 12 },
  heading: { fontSize: 11, fontWeight: 700, marginBottom: 4 },
  blank: { backgroundColor: "#FEF3C7" },
  signatures: { flexDirection: "row", gap: 32, marginTop: 28 },
  signBox: { flex: 1 },
  signLine: { borderBottomWidth: 1, borderBottomColor: "#202124", height: 36, marginBottom: 6 },
  footer: { position: "absolute", bottom: 28, left: 56, right: 56, fontSize: 8, color: "#80868B" },
});

// Splits text so "[Client's postal address]"-style blanks can be highlighted.
function TextWithBlanks({ text }: { text: string }) {
  return (
    <Text>
      {text.split(/(\[[^\]]+\])/g).map((part, i) =>
        part.startsWith("[") && part.endsWith("]") ? (
          <Text key={i} style={styles.blank}>
            {part}
          </Text>
        ) : (
          part
        ),
      )}
    </Text>
  );
}

export default function ContractPdf({ contract }: { contract: Contract }) {
  return (
    <Document title={contract.title} author="Sage">
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>{contract.title}</Text>

        {contract.clauses.map((clause) => (
          // wrap={false} keeps a short clause from splitting across two pages.
          <View key={clause.id} style={styles.clause} wrap={clause.text.length > 900}>
            <Text style={styles.heading}>
              {clause.number}. {clause.title}
            </Text>
            <TextWithBlanks text={clause.text} />
          </View>
        ))}

        <View style={styles.signatures} wrap={false}>
          {contract.parties.map((party) => (
            <View key={party.role} style={styles.signBox}>
              <View style={styles.signLine} />
              <Text>Signed by the {party.role}</Text>
              <Text>Name: {party.name}</Text>
              <Text>Date:</Text>
            </View>
          ))}
        </View>

        <Text
          style={styles.footer}
          fixed
          render={({ pageNumber, totalPages }) =>
            `Generated by Sage. Not legal advice. Page ${pageNumber} of ${totalPages}`
          }
        />
      </Page>
    </Document>
  );
}
